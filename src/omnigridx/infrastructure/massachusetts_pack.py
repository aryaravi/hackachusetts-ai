_DISCOVERY_URL = "https://hackachusetts2026.vercel.app/#/climate"
_PACK_VERSION = "2026.1"
_RETRIEVED_AT = Timestamp(datetime(2026, 2, 1, tzinfo=UTC))


def _source(
    identifier: str,
    publisher: str,
    canonical_url: str,
    dataset_identifier: str,
    categories: tuple[str, ...],
    units: tuple[str, ...],
    cadence: str,
    coverage: str,
    allowed_uses: tuple[str, ...],
    prohibited_uses: tuple[str, ...],
) -> SnapshotSourceDeclaration:
    return SnapshotSourceDeclaration(
        source=SourceRecord(
            identifier=Identifier(identifier),
            publisher=publisher,
            canonical_url=canonical_url,
            discovery_url=_DISCOVERY_URL,
            dataset_identifier=Identifier(dataset_identifier),
            retrieved_at=_RETRIEVED_AT,
            version_or_as_of=f"pack-metadata-{_PACK_VERSION}",
            geography="Massachusetts",
            units=units,
            cadence=cadence,
            coverage=coverage,
            access_terms="Publisher terms apply; confirm before production use",
            quality_status="approved snapshot metadata; source values not bundled",
            allowed_uses=allowed_uses,
            prohibited_uses=prohibited_uses,
        ),
        categories=categories,
        snapshot_version=_PACK_VERSION,
        local_uri=f"local://massachusetts/{_PACK_VERSION}/{identifier}.json",
    )


